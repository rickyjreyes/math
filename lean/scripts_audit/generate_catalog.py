#!/usr/bin/env python3
"""Regenerate or check the Lean navigation catalogue; never edit proof sources."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CAT = ROOT / "catalog"

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated pages are stale")
    args = parser.parse_args()
    groups = json.loads((CAT / "topics.json").read_text(encoding="utf-8"))
    modules = sorted(p.stem for p in (ROOT / "MathProofs").glob("*.lean"))
    imports = re.findall(r"^import MathProofs\.(\w+)\s*$", (ROOT / "MathProofs.lean").read_text(encoding="utf-8"), re.M)
    if len(imports) != len(set(imports)) or set(imports) - set(modules):
        raise SystemExit("Duplicate or unresolved direct master imports")
    assigned = {g["id"]: [] for g in groups}
    for n in modules:
        matches = [g for g in groups if n in g["names"] or any(n.startswith(p) for p in g["prefixes"])]
        if len(matches) != 1:
            raise SystemExit(f"{n}: expected exactly one topic, found {len(matches)}; update catalog/topics.json")
        assigned[matches[0]["id"]].append(n)
    audits = sorted(
        [p.relative_to(ROOT).as_posix() for p in ROOT.glob("*Audit.lean")]
        + [p.relative_to(ROOT).as_posix() for p in (ROOT / "scripts_audit").iterdir()
           if p.is_file() and p.suffix in {".lean", ".py"} and p.name != Path(__file__).name]
        + ["scripts_audit/generate_catalog.py"]
    )
    pages = {}
    index = "# Lean proof catalogue\n\nGenerated by `python scripts_audit/generate_catalog.py` from `MathProofs/`, `MathProofs.lean` and `catalog/topics.json`. Run from `lean/`. This is a source inventory, not a kernel-verification or manuscript-completion certificate.\n\n"
    index += f"**{len(modules)} proof source modules · {len(imports)} direct imports · {len(modules)-len(imports)} other source modules.**\n\n| Subject | Modules |\n|---|---:|\n"
    for g in groups:
        ns = assigned[g["id"]]
        index += f"| [{g['title']}]({g['id']}.md) | {len(ns)} |\n"
        page = f"# {g['title']}\n\n{g['description']}\n\n[Back to catalogue](README.md)\n\n**{len(ns)} source modules.**\n\n| Module | Direct master import |\n|---|---|\n"
        for n in ns:
            status = "Yes" if n in imports else "Not listed directly"
            page += f"| [`MathProofs.{n}`](../MathProofs/{n}.lean) | {status} |\n"
        if not ns:
            page += "\nNo matching modules at this revision.\n"
        pages[g["id"] + ".md"] = page
    index += "\n## Verification and build files\n\n"
    for path in audits:
        index += f"- [`{path}`](../{path})\n"
    index += "\n- [Master import file](../MathProofs.lean)\n- [Pinned Lake configuration](../lakefile.lean) and [Lean toolchain](../lean-toolchain)\n- [Manuscript-level status manifest](../formalization.yaml)\n- [Formalization guide](../README.md)\n\nA module absent from the direct import list may be imported transitively; consult the dependency graph and actual build. Do not equate presence in this catalogue with verification.\n"
    pages["README.md"] = index
    stale = []
    for name, content in pages.items():
        path = CAT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(name)
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit("Stale catalogue: " + ", ".join(stale))
    print(f"Catalogue: {len(modules)} sources, {len(imports)} direct imports, {len(groups)} topics")

if __name__ == "__main__":
    main()
