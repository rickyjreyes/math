#!/usr/bin/env python3
"""Generate explicit Lean proof scripts, not trusted numerical certificates.

Every interval calculation below is rechecked by Lean's `norm_num`; the
transcendental bounds follow from Mathlib's proved pi and Taylor bounds.
Run from any directory to regenerate V18MiddleEnclosures.lean.
"""
from fractions import Fraction as F
from math import ceil, floor
from pathlib import Path
from itertools import permutations

from v18_middle_rational_taylor_certificate import I, NS, ROT1, ROT2

ROOT = Path(__file__).resolve().parents[1]
PI = I(F("3.141592"), F("3.141593"))


def q(x):
    x = F(x)
    return str(x.numerator) if x.denominator == 1 else f"({x.numerator} / {x.denominator})"


def rounded(z):
    return I(F(floor(z.lo * 10000), 10000), F(ceil(z.hi * 10000), 10000))


def b(z, expr):
    return f"Bounds ({q(z.lo)}) ({q(z.hi)}) ({expr})"


def angle(n, k, harmonic=False):
    expr = f"(9.4062 : ℝ) * {n}" if harmonic else f"(5.0632 : ℝ) * {n} + 1.6469"
    x = F("9.4062") * n if harmonic else F("5.0632") * n + F("1.6469")
    r = I.point(x) - PI.scale(F(k, 2))
    r2, r3 = r*r, (r*r)*r
    radius = max(abs(r.lo), abs(r.hi))
    error = F(5, 96) * radius**4
    s = rounded(r - r3.scale(F(1, 6)) + I(-error, error))
    c = rounded(I.point(1) - r2.scale(F(1, 2)) + I(-error, error))
    out_s, out_c = ((s, c), (c, -s), (-s, -c), (-c, s))[k % 4]
    rot = "r" if k % 2 == 0 else "(r + Real.pi / 2)"
    sign_s = ("hs", "hc", "hs.neg", "hc.neg")[k % 4]
    sign_c = ("hc", "hs.neg", "hc.neg", "hs")[k % 4]
    name = f"{'harmonic' if harmonic else 'primary'}_{n}"
    proof = f"""
/-- Rational enclosures of the exact frozen trigonometric arguments at n={n}. -/
theorem {name} :
    {b(out_s, f'Real.sin ({expr})')} ∧
    {b(out_c, f'Real.cos ({expr})')} := by
  let r : ℝ := {expr} - {q(F(k, 2))} * Real.pi
  have hr : {b(r, 'r')} := by
    constructor <;> dsimp [r] <;> nlinarith [Real.pi_gt_d6, Real.pi_lt_d6]
  have hr2 : {b(r2, 'r * r')} := by
    convert hr.mul hr using 1 <;> norm_num
  have hr3 : {b(r3, '(r * r) * r')} := by
    convert hr2.mul hr using 1 <;> norm_num
  have habs : |r| ≤ {q(radius)} := by
    apply abs_le.mpr
    constructor <;> linarith [hr.1, hr.2]
  have hunit : |r| ≤ 1 := habs.trans (by norm_num)
  have hfour : |r| ^ 4 ≤ ({q(radius)} : ℝ) ^ 4 :=
    pow_le_pow_left₀ (abs_nonneg r) habs 4
  have hs0 := abs_le.mp (Real.sin_bound hunit)
  have hc0 := abs_le.mp (Real.cos_bound hunit)
  have hs : {b(s, 'Real.sin r')} := by
    constructor <;> nlinarith [hr.1, hr.2, hr3.1, hr3.2, hs0.1, hs0.2]
  have hc : {b(c, 'Real.cos r')} := by
    constructor <;> nlinarith [hr2.1, hr2.2, hc0.1, hc0.2]
  have harg : {rot} + ({k // 2} : ℕ) * Real.pi = {expr} := by dsimp [r]; ring
  have hsrot := Real.sin_add_nat_mul_pi {rot} {k // 2}
  have hcrot := Real.cos_add_nat_mul_pi {rot} {k // 2}
  rw [harg] at hsrot hcrot
  norm_num [Real.sin_add_pi_div_two, Real.cos_add_pi_div_two] at hsrot hcrot
  norm_num only
  rw [hsrot, hcrot]
  constructor
  · convert {sign_s} using 1 <;> norm_num
  · convert {sign_c} using 1 <;> norm_num
"""
    return proof, (out_s, out_c)


def main():
    out = """import MathProofs.V18Interval

/-!
# Rational enclosures of the frozen middle-sector trigonometric entries

Generated by `scripts/generate_v18_middle_lean.py`. All calculations are checked
by the Lean kernel. Inputs: `Real.pi_gt_d6`, `Real.pi_lt_d6`, `Real.sin_bound`,
and `Real.cos_bound`. The Python generator is not part of the trusted base.
-/

namespace ReyesMath.V18MiddleEnclosures
open V18Interval
set_option maxHeartbeats 800000
"""
    for n, k in zip(NS, ROT1):
        out += angle(n, k)[0]
    for n, k in zip(NS, ROT2):
        out += angle(n, k, True)[0]
    out += "\nend ReyesMath.V18MiddleEnclosures\n"
    (ROOT / "lean/MathProofs/V18MiddleEnclosures.lean").write_text(out)
    determinant()


def determinant():
    names = [f"{c}{i}" for c in ('s', 'b', 't') for i in range(5)]
    entries = {}
    for i, (n, k1, k2) in enumerate(zip(NS, ROT1, ROT2)):
        _, (s, c) = angle(n, k1)
        _, (t, _) = angle(n, k2, True)
        entries[f's{i}'], entries[f'b{i}'], entries[f't{i}'] = s, c.scale(F('2241.1')), t
    shape = '!![' + ';\n      '.join(
        f'(1 : ℝ), {n*n}, s{i}, b{i}, t{i}' for i, n in enumerate(NS)) + ']'
    coefficients = {}
    for p in permutations(range(5)):
        sign = (-1) ** sum(p[i] > p[j] for i in range(5) for j in range(i+1, 5))
        key = p[2:]
        coefficients[key] = coefficients.get(key, 0) + sign * NS[p[1]]**2
    terms = [(f'({c} : ℝ) * ((s{i} * b{j}) * t{k})', c, i, j, k)
             for (i, j, k), c in sorted(coefficients.items())]
    poly = ' +\n      '.join(t[0] for t in terms)
    four_terms = []
    for p in permutations(range(4)):
        sign = (-1) ** sum(p[i] > p[j] for i in range(4) for j in range(i+1, 4))
        four_terms.append(f"({sign} : ℝ) * " + ' * '.join(f'A {p[j]} {j}' for j in range(4)))
    four_poly = ' +\n      '.join(four_terms)
    def minor_eqs(size, var):
        result = ''
        for i in range(size):
            mat = '!![' + '; '.join(', '.join(f'{var} {r} {c}' for c in range(1, size))
                                  for r in range(size) if r != i) + ']'
            result += f'  have hm{i} : {var}.submatrix ({i} : Fin {size}).succAbove Fin.succ =\n      {mat} := by\n    ext i j; fin_cases i <;> fin_cases j <;> rfl\n'
        return result
    def tri(rows):
        a, d, g = [[f'A {r} {c}' for c in range(1, 4)] for r in rows]
        return (f'{a[0]} * {d[1]} * {g[2]} - {a[0]} * {d[2]} * {g[1]} - '
                f'{a[1]} * {d[0]} * {g[2]} + {a[1]} * {d[2]} * {g[0]} + '
                f'{a[2]} * {d[0]} * {g[1]} - {a[2]} * {d[1]} * {g[0]}')
    four_laplace = ' +\n      '.join(f'(-1 : ℝ)^{i} * A {i} 0 * ({tri([r for r in range(4) if r != i])})' for i in range(4))
    four_proof = minor_eqs(4, 'A') + f"  rw [Matrix.det_succ_column_zero]\n  rw [Fin.sum_univ_four]\n  rw [hm0, hm1, hm2, hm3]\n  simp only [Matrix.det_fin_three]\n  change {four_laplace} = _\n  ring\n"
    five_proof = f'  let A : Matrix (Fin 5) (Fin 5) ℝ := {shape}\n' + minor_eqs(5, 'A')
    rows = [[str(n*n), f's{i}', f'b{i}', f't{i}'] for i, n in enumerate(NS)]
    five_parts = []
    for i in range(5):
        minor = [row for j, row in enumerate(rows) if j != i]
        parts = []
        for p in permutations(range(4)):
            sign = (-1) ** sum(p[j] > p[k] for j in range(4) for k in range(j+1, 4))
            parts.append(f'({sign} : ℝ) * ' + ' * '.join(minor[p[j]][j] for j in range(4)))
        five_parts.append(f'(-1 : ℝ)^{i} * 1 * (' + ' + '.join(parts) + ')')
    five_laplace = ' +\n      '.join(five_parts)
    five_proof += f'  change A.det = _\n  rw [Matrix.det_succ_column_zero]\n  rw [Fin.sum_univ_five]\n  rw [hm0, hm1, hm2, hm3, hm4]\n  simp only [det_four]\n  change {five_laplace} = _\n  ring'
    out = f"""import MathProofs.V18MiddleJacobian
import MathProofs.V18MiddleEnclosures

/-!
# Kernel certificate for the actual frozen 5×5 middle determinant

Generated by `scripts/generate_v18_middle_lean.py`. `det_shape` is an exact
polynomial identity; every interval endpoint is subsequently checked by Lean.
No result of executing the generator is used as an assumption.
-/

noncomputable section
namespace ReyesMath.V18MiddleJacobian
open V18Interval V18MiddleEnclosures
set_option maxRecDepth 16384
set_option maxHeartbeats 2000000

private theorem det_four (A : Matrix (Fin 4) (Fin 4) ℝ) :
    A.det =
      {four_poly} := by
{four_proof}
private theorem det_shape ({' '.join(names)} : ℝ) :
    ({shape}).det =
      {poly} := by
{five_proof}

private theorem det_shape_bounds {{{' '.join(names)} : ℝ}}
"""
    for name in names:
        out += f'    (h{name} : {b(entries[name], name)})\n'
    bounds = [I.point(c) * ((entries[f's{i}'] * entries[f'b{j}']) * entries[f't{k}'])
              for _, c, i, j, k in terms]
    total = sum(bounds, I.point(0))
    out += f'    : {b(total, f"({shape}).det")} := by\n'
    for idx, ((term, c, i, j, k), bound) in enumerate(zip(terms, bounds)):
        out += f"""  have h{idx} : {b(bound, term)} := by
    convert (Bounds.point ({c} : ℝ)).mul ((hs{i}.mul hb{j}).mul ht{k}) using 1 <;> norm_num
"""
    proof = 'h0'
    for idx in range(1, len(terms)):
        proof = f'({proof}.add h{idx})'
    out += f'  have h := {proof}\n  rw [det_shape]\n  convert h using 1 <;> norm_num\n'
    out += """
/-- A rational, strictly positive enclosure of the determinant of `middle`
itself, with the source's exact decimal arguments and amplitude. -/
theorem middle_det_bounds :
    (18000000 : ℝ) < middle.det ∧ middle.det < 24000000 := by
"""
    for i, n in enumerate(NS):
        out += f'  have hs{i} := (primary_{n}).1\n'
        out += f'  have hb{i} : {b(entries[f"b{i}"], f"(2241.1 : ℝ) * Real.cos ((5.0632 : ℝ) * {n} + 1.6469)")} := by\n'
        out += f'    convert (Bounds.point (2241.1 : ℝ)).mul (primary_{n}).2 using 1 <;> norm_num\n'
        out += f'  have ht{i} := (harmonic_{n}).1\n'
    out += '  have h := det_shape_bounds ' + ' '.join(f'h{name}' for name in names) + '\n'
    out += '  change Bounds _ _ middle.det at h\n'
    out += '  constructor <;> linarith only [h.1, h.2]\n'
    out += """
theorem middle_det_pos : 0 < middle.det := lt_trans (by norm_num) middle_det_bounds.1

theorem middle_det_ne_zero : middle.det ≠ 0 := ne_of_gt middle_det_pos

/-- Unconditional nonsingularity of the product of the three frozen blocks.
Identification with the full observation derivative is a separate obligation. -/
theorem determinant_product_nonzero (alpha epsilon : ℝ) :
    (V18LightJacobian.minor alpha epsilon).det *
      middle.det * V18HeavyJacobian.heavy.det ≠ 0 :=
  determinant_product_nonzero_of_middle alpha epsilon middle_det_ne_zero

end ReyesMath.V18MiddleJacobian
"""
    (ROOT / 'lean/MathProofs/V18MiddleDeterminant.lean').write_text(out)
    print('Generated determinant enclosure:', float(total.lo), float(total.hi))


if __name__ == "__main__":
    main()
